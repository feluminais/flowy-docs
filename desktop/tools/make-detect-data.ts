// Writes desktop/Flowy.Core/DetectData.cs from src/core/detect.ts, so the app tells languages apart with the same cues as the browser.
// Run from the repo root after changing the cue table: node desktop/tools/make-detect-data.ts
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { CPP_ONLY, CUES, MIN_SCORE, YAML_BUT_CODE } from '../../src/core/detect.ts'

const verbatim = (s: string) => `@"${s.replaceAll('"', '""')}"`
const field = (name: string, re: RegExp) =>
  `    public static readonly Regex ${name} = Rx(${verbatim(re.source)}, ${re.flags.includes('i')}${re.flags.includes('m') ? '' : ', multiline: false'});`

/** The text of DetectData.cs. A test compares it with the file, so the two never drift apart. */
export function renderDetectData(): string {
  const rows = CUES.flatMap(({ language, cues }) => [
    `        ("${language}", [`,
    ...cues.map(([re, weight]) => `            (Rx(${verbatim(re.source)}, ${re.flags.includes('i')}), ${weight}),`),
    '        ]),',
  ])
  return [
    '// Generated by desktop/tools/make-detect-data.ts from src/core/detect.ts. Do not edit; change that and run the script again.',
    'using System.Text.RegularExpressions;',
    '',
    'namespace Flowy.Core;',
    '',
    '/// <summary>The cues that tell a language: a pattern and what a match is worth, for each language in the order src/core/detect.ts lists them.</summary>',
    'public static class DetectData',
    '{',
    '    // ECMAScript mode gives \\w, \\s and \\b the meanings they have in JavaScript, which is where the patterns were written.',
    '    private static Regex Rx(string pattern, bool ignoreCase, bool multiline = true) =>',
    '        new(pattern, RegexOptions.ECMAScript | (multiline ? RegexOptions.Multiline : RegexOptions.None) | (ignoreCase ? RegexOptions.IgnoreCase : RegexOptions.None));',
    '',
    '    /// <summary>The least weight that is enough to name a language.</summary>',
    `    public const int MinScore = ${MIN_SCORE};`,
    '',
    '    /// <summary>A line that ends in a semicolon or an opening brace, or a lone closing brace: code, so it counts against YAML.</summary>',
    field('YamlButCode', YAML_BUT_CODE),
    '',
    '    /// <summary>What only C++ has. Code the cues call C++ that has none of these is C.</summary>',
    field('CppOnly', CPP_ONLY),
    '',
    '    public static readonly (string Language, (Regex Pattern, int Weight)[] Cues)[] Cues =',
    '    [',
    ...rows,
    '    ];',
    '}',
    '',
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('../Flowy.Core/DetectData.cs', import.meta.url), renderDetectData())
  console.log(`wrote ${CUES.length} languages, ${CUES.reduce((n, l) => n + l.cues.length, 0)} cues`)
}
